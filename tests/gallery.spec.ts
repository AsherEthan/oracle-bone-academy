  await page.getByRole('button', { name: '看看字头 142', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '字头 142 · 字形与材料' })
  await expect(dialog.locator('.detail-title-row h2')).toHaveText('字头 142')
  await expect(dialog.locator('.detail-pinyin, .character-story, .look-closer')).toHaveCount(0)
  await expect(dialog.getByText('原来是一只脚', { exact: true })).toHaveCount(0)
