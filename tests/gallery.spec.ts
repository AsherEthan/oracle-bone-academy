import { expect, test } from '@playwright/test'
import corpus from '../src/data/corpus.json' with { type: 'json' }
import curated from '../src/data/curated-headwords.json' with { type: 'json' }

const headwordCount = new Set([...corpus.records.map(record => record.order), ...curated.map(record => record.order)]).size
const headFor = (char: string) => curated.find(record => record.char === char)?.order ?? corpus.records.find(record => record.labels.includes(char))!.order

test('home shows a bounded page of real forms rather than thousands of mounted cards', async ({ page }, testInfo) => {
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!new URL(request.url()).hostname.match(/^(127\.0\.0\.1|localhost)$/)) external.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: '先看字形，再找线索。' })).toBeVisible()
  await expect(page.locator('.glyph-card')).toHaveCount(48)
  await expect(page.locator('.card-character').first()).toHaveText('字头 806')
  await expect(page.locator('.card-pinyin')).toHaveCount(0)
  await expect(page.locator('.card-caption').first()).toContainText('目录标签 · 日')
  await expect(page.locator('.card-caption').first()).not.toContainText('一轮太阳')
  await expect(page.locator('.glyph-card .source-glyph')).toHaveCount(48)
  await expect(page.locator('.browse-result-line')).toContainText(`${headwordCount.toLocaleString()} 个字头`)
  await expect(page.locator('.glyph-unavailable, .source-scope, .correction-note, .hero')).toHaveCount(0)
  await expect.poll(() => page.locator('.source-glyph').first().evaluate(image => (image as HTMLImageElement).naturalWidth > 0)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ animations: 'disabled', path: `artifacts/corpus-home-${testInfo.project.name}.png` })
  expect(errors).toEqual([])
  expect(external).toEqual([])
})

test('search covers the expanded catalogue and does not show fabricated fallback cards', async ({ page }) => {
  await page.goto('/')
  const search = page.getByRole('textbox', { name: '搜索标签、拼音或编号' })
  for (const [query, char] of [['shui', '水'], ['魚', '鱼'], ['眼睛', '目'], ['木', '木']]) {
    await search.fill(query)
    await expect(page.getByRole('button', { name: `看看字头 ${headFor(char)}`, exact: true }).first()).toBeVisible()
    await expect(page.locator('.search-material-note')).toContainText('不表示古今字等同')
    await expect(page.locator('.glyph-unavailable')).toHaveCount(0)
  }
  await search.fill('不存在的字XYZ')
  await expect(page.getByRole('heading', { name: '还没找到这个字。' })).toBeVisible()
  await expect(page.locator('.glyph-card')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '随遇一字' })).toBeDisabled()
  await page.getByRole('button', { name: '清除筛选' }).click()
  await expect(page.locator('.glyph-card')).toHaveCount(48)
})

test('new native-range records show their own source image and survive bookmarking', async ({ page }) => {
  const record = corpus.records.find(entry => entry.order === 3500)
  test.skip(!record, 'The native-range acquisition has not been imported yet')
  if (!record) return
  const example = record.examples[0]
  await page.goto('/')
  await page.getByRole('textbox', { name: '搜索标签、拼音或编号' }).fill(example.code)
  await page.getByRole('button', { name: '看看字头 3500', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('.detail-title-row h2')).toHaveText('字头 3500')
  await expect(dialog.locator('.record-materials')).toContainText(example.code)
  await expect(dialog.locator('.record-materials')).toContainText(example.reference)
  await expect(dialog.locator('.detail-glyph-wrap img')).toHaveAttribute('src', `/glyph-sources/sinica-corpus-20261031/glyph-${example.code.toLowerCase().replace('.', '-')}/image.png`)
  await expect.poll(() => dialog.locator('.detail-glyph-wrap img').evaluate(image => (image as HTMLImageElement).naturalWidth > 0)).toBe(true)
  await expect(dialog.locator('.detail-pinyin, .character-story, .reference-materials')).toHaveCount(0)
  await expect(dialog.locator('.record-materials a')).toHaveAttribute('href', `https://xiaoxue.iis.sinica.edu.tw/char?fontcode=${example.code}`)
  await dialog.getByRole('button', { name: '收藏字头 3500', exact: true }).click()
  await page.keyboard.press('Escape')
  await page.reload()
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: /拾字簿/ }).click()
  await expect(page.getByRole('button', { name: '看看字头 3500', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('zizai.collection.v1')!))).toContain('sinica-jgw-3500')
})

test('pagination reaches the last native headword and filters reset it', async ({ page }) => {
  await page.goto('/')
  const first = await page.locator('.card-open').first().getAttribute('aria-label')
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(page.locator('.card-open').first()).not.toHaveAttribute('aria-label', first!)
  await expect(page.getByRole('combobox', { name: '选择字库页码' })).toHaveValue('2')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const last = String(Math.ceil(headwordCount / 48))
  await page.getByRole('combobox', { name: '选择字库页码' }).selectOption(last)
  await expect(page.locator('.glyph-card')).toHaveCount(headwordCount % 48 || 48)
  await expect(page.getByRole('button', { name: '下一页', exact: true })).toBeDisabled()
  await expect.poll(() => page.locator('.glyph-card img').first().evaluate(image => (image as HTMLImageElement).naturalWidth > 0)).toBe(true)
  await page.getByRole('button', { name: '有参考材料', exact: true }).click()
  await expect(page.locator('.glyph-card')).toHaveCount(12)
  await expect(page.getByRole('navigation', { name: '字库分页' })).toHaveCount(0)
  await page.getByRole('button', { name: '全部', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '选择字库页码' })).toHaveValue('1')
})

