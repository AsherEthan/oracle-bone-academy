test('legacy modern-character bookmarks resolve to source-native IDs without silently dropping selections', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('zizai.collection.v1', '["木","止"]'))
  await page.goto('/')
  await page.getByRole('navigation', { name: '主导航' }).getByRole('button', { name: /拾字簿/ }).click()
  await expect(page.locator('.glyph-card')).toHaveCount(2)
  await expect(page.getByRole('button', { name: '看看字头 142', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: `看看字头 ${headFor('木')}`, exact: true })).toBeVisible()
  await expect(page.locator('.glyph-unavailable')).toHaveCount(0)
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('zizai.collection.v1')!))).toEqual(['木', '止'])
  await page.getByRole('button', { name: `取消收藏字头 ${headFor('木')}`, exact: true }).click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('zizai.collection.v1')!))).toEqual(['sinica-jgw-142'])
})

