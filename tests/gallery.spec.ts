  await expect(dialog.locator('.record-materials')).toContainText('甲1440 合31080')
  await expect(dialog.locator('.reference-materials')).toContainText('13688')
  await expect(dialog.locator('.reference-materials')).toContainText('不是本页摹本')
  await expect(dialog.locator('.detail-sources')).toHaveJSProperty('open', false)
  await page.screenshot({ animations: 'disabled', path: `artifacts/materials-stop-${testInfo.project.name}.png` })
  await dialog.locator('.detail-sources > summary').click()
  await expect(dialog.getByRole('link', { name: '查看字例页', exact: true })).toHaveAttribute('href', 'https://xiaoxue.iis.sinica.edu.tw/char?fontcode=41.E74A')
  await expect(dialog.getByRole('button', { name: '关闭弹窗' }).filter({ visible: true })).toBeInViewport()
  await dialog.locator('.example-strip button').nth(1).click()
  await expect(dialog.locator('.detail-sources')).toHaveJSProperty('open', false)
  await dialog.locator('.detail-sources > summary').click()
  await expect(dialog.getByRole('link', { name: '查看字例页', exact: true })).not.toHaveAttribute('href', 'https://xiaoxue.iis.sinica.edu.tw/char?fontcode=41.E74A')
